// 把 src/client/*.js 与两个共用模块拼成宿主可加载的单文件 Client 产物。
// 无第三方依赖；改完前端跑一次 node scripts/build-client.mjs。
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const ID = '@local/lumina-kitchen'

async function read(rel) {
  return readFile(join(root, rel), 'utf8')
}

/** 共用模块在客户端是内联副本：去掉 export 关键字即可。 */
function inline(rel, source) {
  return `// --- inlined from ${rel} ---\n${source.replace(/^export /gm, '')}\n`
}

const FRAGMENTS = ['00-head.js', '10-atlas.js', '15-motion.js', '80-workbench.js', '85-guided.js', '86-onboarding.js', '87-results.js', '88-shell.js', '88-create.js', '89-experiments.js', '89-services.js', '90-app.js']

const parts = []
parts.push(inline('src/lab-input.js', await read('src/lab-input.js')))
parts.push(inline('src/taste.js', await read('src/taste.js')))
parts.push(inline('src/build.js', await read('src/build.js')))
for (const name of FRAGMENTS) {
  parts.push(`// --- ${name} ---\n${await read(`src/client/${name}`)}`)
}

const body = parts.join('\n')

const out = `/* LUMINA video kitchen — generated by scripts/build-client.mjs. Do not edit by hand. */
window.__ModuleLoader__.load({
  id: '${ID}',
  factory(require) {
    const module = { exports: {} };
    const exports = module.exports;
    const React = require('react');
${body}
    return module.exports;
  },
});
`

await mkdir(join(root, 'dist'), { recursive: true })
await writeFile(join(root, 'dist', 'client.js'), out, 'utf8')
console.log(`dist/client.js written (${out.length} bytes, ${FRAGMENTS.length + 2} parts)`)
